"""``ifdd-meta compile``: from a short description to the complete files.

The values come from ``data/defaults.yaml``; the compiler replaces the derived
ones (host names, URLs, realm endpoints, TLS mode, login gate, CSPs) and then
applies the overrides of the description. The output is explicit: every
template variable except the versions (rule B.3).
"""

from __future__ import annotations

import json
from dataclasses import dataclass
from importlib.resources import files
from pathlib import Path

import jinja2
import yaml

from . import yamltext
from .catalogue import (
    CA_BUNDLE,
    DASHBOARD_LABEL,
    GIT_LABEL,
    GIT_REPOSITORY,
    GIT_USER,
    HOST_LABELS,
    LAB_CLIENT_ID,
)
from .description import Description

VARIABLES_FILE = "cookiecutter_all.yaml"
SETTINGS_FILE = "ifdd-meta.yaml"
ENV_EXAMPLE_FILE = ".env.example"
HOSTS_FILE = "hosts.txt"
OUTPUT_FILES = (VARIABLES_FILE, SETTINGS_FILE, ENV_EXAMPLE_FILE, HOSTS_FILE)


class CompileError(ValueError):
    """The description cannot be compiled."""


@dataclass(frozen=True)
class Result:
    values: dict[str, str | list[str]]
    files: dict[str, str]  # file name -> text
    warnings: tuple[str, ...] = ()


SHORT_NAMES_WITH_WF = (
    "short host names (no hosts.suffix) with wf: Java clients such as Kestra send no "
    "server name (SNI) for names without a dot, and the proxy refuses such handshakes in "
    "production (sniStrict), so the Git synchronisation of wf fails; set hosts.suffix, "
    "e.g. to a .test domain"
)


def defaults_text() -> str:
    return files("ifdd_meta").joinpath("data/defaults.yaml").read_text(encoding="utf-8")


def compile_description(description: Description, defaults: str | None = None) -> Result:
    text = defaults if defaults is not None else defaults_text()
    document = yamltext.parse(text)
    values: dict[str, str | list[str]] = yaml.safe_load(text)["default_context"]

    # Derived values see the overrides (e.g. a renamed lab network); overrides still win.
    derived = derive(description, {**values, **description.overrides})
    values.update(derived)
    unknown = sorted(set(description.overrides) - set(values))
    if unknown:
        raise CompileError(f"overrides of unknown variables: {', '.join(unknown)}")
    for key, value in description.overrides.items():
        if isinstance(values[key], list) != isinstance(value, list):
            kind = "a list" if isinstance(values[key], list) else "a text"
            raise CompileError(f"overrides.{key}: expected {kind}")
        if isinstance(value, list) and sorted(value) != sorted(values[key]):
            raise CompileError(
                f"overrides.{key}: a choice lists the same entries in another order, "
                f"the selected one first: {', '.join(values[key])}"
            )
    values.update(description.overrides)

    name = description.path.name
    head = [
        f"# Generated by 'ifdd-meta compile' from {name}; do not edit.",
        "# Change the description or its overrides and compile again.",
        "",
        "default_context:",
    ]
    short_names = not description.suffix and not description.names
    warnings = (SHORT_NAMES_WITH_WF,) if short_names and "wf" in description.services else ()
    return Result(
        warnings=warnings,
        values=values,
        files={
            VARIABLES_FILE: yamltext.render(document, values, head),
            SETTINGS_FILE: _settings(description, name),
            ENV_EXAMPLE_FILE: _env_example(description, name),
            HOSTS_FILE: _hosts(description, name),
        },
    )


def derive(description: Description, values: dict) -> dict[str, str]:
    """Values computed from the description (marked "derived" in the defaults)."""
    d = description
    host = d.host
    services = set(d.services)
    realm_url = f"https://{host('id')}/realms/{d.realm}"
    endpoint = f"{realm_url}/protocol/openid-connect"
    url = {label: f"https://{host(label)}" for label in HOST_LABELS.values()}
    gate_on = "wf" in services and values["ifdd_wf_enable_sso"] == "y"
    backend_client = values["ifdd_oidc_backend_client_id"]
    proxy_slug = _render(values["ifdd_proxy_prj_slug"], values)

    internal = _internal_hosts(d)
    origins_ui = " ".join([url["id"], url["rest"], url["type"], url["unit"]])
    return {
        # hosts and URLs
        "ifdd_proxy_internal_hosts": ", ".join(internal),
        "ifdd_proxy_host": host(DASHBOARD_LABEL),
        "ifdd_keycloak_host": host("id"),
        "ifdd_be_host": host("rest"),
        "ifdd_be_url": url["rest"],
        "ifdd_ui_host": host("ui"),
        "ifdd_ui_url": url["ui"],
        "ifdd_schema_host": host("schema"),
        "ifdd_schema_url": f"{url['schema']}/v1",
        "ifdd_type_host": host("type"),
        "ifdd_type_url": f"{url['type']}/v1",
        "ifdd_unit_host": host("unit"),
        "ifdd_unit_url": f"{url['unit']}/v1",
        "ifdd_ts_host": host("ts"),
        "ifdd_ts_api_url": f"{url['ts']}{values['ifdd_ts_api_path']}",
        "ifdd_ts_be_url": url["rest"],
        "ifdd_wf_host": host("wf"),
        "ifdd_lab_host": host("lab"),
        "ifdd_model_host": host("model"),
        # realm
        "ifdd_keycloak_realm": d.realm,
        "ifdd_keycloak_extra_realms": ", ".join(d.extra_realms),
        "ifdd_oidc_realm": realm_url,
        "ifdd_proxy_oidc_issuer": realm_url,
        "ifdd_ts_oidc_issuer": realm_url,
        "ifdd_oidc_token_url": f"{endpoint}/token",
        "ifdd_oidc_refresh_url": f"{endpoint}/token",
        "ifdd_oidc_authorization_url": f"{endpoint}/auth",
        "ifdd_oidc_jwks_url": f"{endpoint}/certs",
        "ifdd_oidc_client_id": backend_client,
        "ifdd_oidc_jwks_audience": backend_client,
        "ifdd_context_root": d.context_root,
        # TLS and login gate
        "ifdd_proxy_enable_letsencrypt": "y" if d.tls == "letsencrypt" else "n",
        "ifdd_proxy_letsencrypt_email": d.contact,
        # oauth2-proxy calls the realm: the local CA, or with ca_certs the bundle
        # that create writes (local CA and ca_certs), or the system store only.
        "ifdd_proxy_oauth2_proxy_ca_file": (
            CA_BUNDLE if d.ca_certs else "" if d.tls == "letsencrypt" else "ca.crt"
        ),
        "ifdd_proxy_enable_oauth2_proxy": "y" if gate_on else "n",
        # always the wf host: the keycloak hook (v26.11.1) rejects an empty value,
        # and a proxy without oauth2-proxy does not use it
        # Empty without wf: no host behind the gate (keycloak 26.11.2 or later).
        "ifdd_keycloak_proxy_gate_hosts": host("wf") if "wf" in description.services else "",
        "ifdd_proxy_oauth2_proxy_service": f"{proxy_slug}-oauth2-proxy",
        # lab: its client in the realm and its internal network, which the proxy
        # joins; empty without lab (no client, no network; keycloak and proxy
        # from their lab release on)
        "ifdd_keycloak_lab_client_id": LAB_CLIENT_ID if "lab" in services else "",
        "ifdd_proxy_extra_networks": values["ifdd_lab_network"] if "lab" in services else "",
        "ifdd_wf_sso_group": values["ifdd_keycloak_wf_admin_group"],
        **_wf_git(d),
        # content security policies: the realm, and for the UI also be, type, unit
        "ifdd_proxy_csp_api_docs": (
            "default-src 'self'; frame-ancestors 'none'; img-src 'self' data:; "
            "style-src 'self' 'unsafe-inline'; script-src 'self'; "
            f"connect-src 'self' {url['id']}; worker-src 'self' blob:"
        ),
        "ifdd_proxy_csp_ui": (
            f"default-src 'self'; frame-ancestors 'none'; frame-src {url['id']}; "
            "img-src 'self' data: blob:; style-src 'self' 'unsafe-inline'; "
            f"font-src 'self' data:; connect-src 'self' {origins_ui}"
        ),
    }


def _local_git(description: Description) -> bool:
    return "wf" in description.services and description.wf_git == "local"


def _internal_hosts(description: Description) -> list[str]:
    """Hosts of the selected services, and the local Git server for wf."""
    names = [description.host(HOST_LABELS[s]) for s in description.services if s in HOST_LABELS]
    if _local_git(description):
        names.append(description.host(GIT_LABEL))
    return names


def _wf_git(description: Description) -> dict[str, str]:
    """With a local Git server: its repository and user; otherwise the defaults or overrides."""
    if not _local_git(description):
        return {}
    url = f"https://{description.host(GIT_LABEL)}/{GIT_USER}/{GIT_REPOSITORY}.git"
    return {"ifdd_wf_git_url": url, "ifdd_wf_git_username": GIT_USER}


def write(result: Result, directory: Path) -> list[Path]:
    directory.mkdir(parents=True, exist_ok=True)
    written = []
    for name, text in result.files.items():
        path = directory / name
        path.write_text(text, encoding="utf-8")
        written.append(path)
    return written


def differences(result: Result, directory: Path) -> list[str]:
    """Names of the output files that are missing or differ on disk."""
    return [
        name
        for name, text in result.files.items()
        if not (directory / name).is_file()
        or (directory / name).read_text(encoding="utf-8") != text
    ]


def _render(template: str, values: dict) -> str:
    return jinja2.Template(template).render(cookiecutter=values)


def _refs(refs: dict[str, str]) -> str:
    if not refs:
        return ""
    return "  refs:\n" + "".join(f"    {service}: {ref}\n" for service, ref in refs.items())


def _settings(description: Description, name: str) -> str:
    services = ", ".join(description.services)
    extra = ""
    if description.external:
        extra += f"external: [{', '.join(description.external)}]\n"
    if "keycloak" in description.external:
        extra += (
            "# Client secrets of the external Keycloak: 'ifdd-meta keycloak secrets' on its\n"
            "# server writes them; keep the file at mode 0600, never in Git.\n"
            "keycloak_secrets: keycloak-secrets.env\n"
        )
    if description.ca_certs:
        extra += "ca_certs:\n" + "".join(f"  - {cert}\n" for cert in description.ca_certs)
    if description.files:
        extra += "# Private files: target in the instance: source (copied by create only)\nfiles:\n"
        extra += "".join(
            f"  {json.dumps(target)}: {json.dumps(source)}\n"
            for target, source in description.files
        )
    return (
        f"# Generated by 'ifdd-meta compile' from {name}; do not edit.\n"
        f"installation: {description.installation}\n"
        f"variables: {VARIABLES_FILE}\n"
        "environment: production\n"
        f"tls: {description.tls}\n"
        "templates:\n"
        "  source: https://github.com/ifdd-de\n"
        f"  ref: {description.ref}\n" + _refs(description.refs) + f"services: [{services}]\n"
        "workdir: work\n"
        "persist: state\n"
        f"wf_git: {description.wf_git}\n"
        f"git_host: {description.host(GIT_LABEL)}\n"
        "# Integration tests (ifdd-meta test): read, or write to add test data\n"
        "tests: read\n" + extra
    )


def _env_example(description: Description, name: str) -> str:
    lines = [
        f"# Generated by 'ifdd-meta compile' from {name}; do not edit.",
        "# Copy to .env next to ifdd-meta.yaml (mode 0600) and fill in the values.",
        "# Secrets never go into Git.",
        "",
        "# Password of the demo user, for 'ifdd-meta demo load'",
        "IFDD_META_DEMO_PASSWORD=",
    ]
    if "wf" in description.services and description.wf_git == "external":
        lines += [
            "",
            "# Token for ifdd_wf_git_url (Git synchronisation of the wf flows)",
            "IFDD_META_WF_GIT_TOKEN=",
        ]
    return "\n".join(lines) + "\n"


def hosts_markers(installation: str) -> tuple[str, str]:
    """First and last line of the /etc/hosts block of an installation."""
    return f"# BEGIN ifdd-meta {installation}", f"# END ifdd-meta {installation}"


def _hosts(description: Description, name: str) -> str:
    """DNS records for a server; an /etc/hosts block for short names or a local CA."""
    names = _internal_hosts(description)
    header = f"# Generated by 'ifdd-meta compile' from {name}; do not edit.\n"
    if (description.suffix or description.names) and description.tls != "local-ca":
        return (
            header
            + "# One DNS record (A, and AAAA with IPv6) per host, pointing to the server.\n"
            + "".join(f"{host}\n" for host in names)
        )
    # The whole file is the block, so that removing the block removes it all.
    begin, end = hosts_markers(description.installation)
    return (
        f"{begin}\n"
        + header
        + "# Block for /etc/hosts of the machine that runs the installation;\n"
        + "# 'ifdd-meta local-setup' prints the commands to add and remove it.\n"
        + f"127.0.0.1 {' '.join(names)}\n{end}\n"
    )
